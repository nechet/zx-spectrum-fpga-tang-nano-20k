#!/usr/bin/env python3
"""Build a small FAT32 card image for tb_fat.v, with the awkward cases in it.

  MBR -> partition (type 0C) at sector 8; 512-byte sectors, 2 sectors per
  cluster, 4 reserved sectors, 2 FATs of 4 sectors, root folder at cluster 2.
  The root folder spans three clusters (2 -> 30 -> 240), and holds a
  volume label, long-name entries, a deleted file, a subfolder and non-game
  files besides the games.  The game files are fragmented: their clusters
  interleave, so reading one means following its chain through the FAT.

Writes tb_fat_image.hex (one byte per line) and tb_fat_expect.vh (the games
the reader should find, in order, with sizes, first clusters and checksums).
"""
import os, random, struct
random.seed(48)
SEC, SPC, RES, NF, FSZ, PART = 512, 2, 4, 2, 4, 8
FAT_LBA = PART + RES
DATA = FAT_LBA + NF * FSZ
NSEC = int(os.environ.get('NSEC', 512))
img = bytearray(NSEC * SEC)
fat = [0] * (FSZ * SEC // 4)
fat[0], fat[1] = 0x0FFFFFF8, 0x0FFFFFFF

def lba(c): return DATA + (c - 2) * SPC
def chk(data):
    c = 0
    for b in data: c = (c * 31 + b) & 0xFFFFFFFF
    return c

# MBR
img[0x1BE + 4] = 0x0C
img[0x1C6:0x1CA] = struct.pack('<I', PART)
img[0x1FE:0x200] = b'\x55\xAA'
# boot sector
v = PART * SEC
img[v:v+3] = b'\xEB\x58\x90'; img[v+3:v+11] = b'MSDOS5.0'
struct.pack_into('<HBHB', img, v + 0x0B, SEC, SPC, RES, NF)
struct.pack_into('<I', img, v + 0x24, FSZ)
struct.pack_into('<I', img, v + 0x2C, 2)
img[v+0x52:v+0x5A] = b'FAT32   '; img[v+0x1FE:v+0x200] = b'\x55\xAA'

# file placement: interleaved cluster lists
free = list(range(3, 30)) + list(range(31, 240))
def place(size, stride):
    n = max(1, -(-size // (SEC * SPC)))
    picks = free[0:n * stride:stride][:n]
    for c in picks: free.remove(c)
    for a, b in zip(picks, picks[1:]): fat[a] = b
    fat[picks[-1]] = 0x0FFFFFFF
    return picks

def entry(name83, attr, clus, size):
    e = bytearray(32)
    assert len(name83) == 11, name83
    e[0:11] = name83.encode('latin1'); e[11] = attr
    struct.pack_into('<H', e, 20, clus >> 16)
    struct.pack_into('<H', e, 26, clus & 0xFFFF)
    struct.pack_into('<I', e, 28, size)
    return e

ents, expect = [], []
ents.append(entry('KRASNODAR  ', 0x08, 0, 0))                 # volume label
games = [('JETPAC  Z80', 10848, 1), ('MANIC   TAP', 3333, 2), ('HORACE  SNA', 49179, 1),
         ('TINY    TAP', 19, 1), ('EXACT   Z80', 2048, 3)]
for i, (nm, size, stride) in enumerate(games):
    if i == 1:
        lfn = bytearray(32); lfn[0] = 0x41; lfn[11] = 0x0F; lfn[1:11] = 'M\0a\0n\0i\0c\0'.encode()
        ents.append(lfn)                                      # a long-name piece
        ents.append(entry('\xE5ELETED TAP', 0x20, 0, 0))     # deleted
        ents.append(entry('README  TXT', 0x20, 0, 100))       # not a game
        ents.append(entry('GAMES      ', 0x10, 0, 0))         # a folder
    if i == 3:                                                # push the rest into cluster 30
        while len(ents) < 2 * SPC * 16 - 1:
            ents.append(entry('PAD%05dBIN' % len(ents), 0x20, 0, 1))
    if nm == 'JETPAC  Z80':                                  # the loader's test snapshot
        data = open('tb_testz80.bin', 'rb').read(); size = len(data)
    elif nm == 'TINY    TAP':                                # the .TAP loader's test tape
        # (TINY_TAP=file puts a real tape in its place, for tb_sdgame.sh)
        data = open(os.environ.get('TINY_TAP', 'tb_testtap.bin'), 'rb').read(); size = len(data)
    else:
        data = bytes(random.randrange(256) for _ in range(size))
    cl = place(size, stride)
    for k in range(len(cl)):
        chunk = data[k * SEC * SPC:(k + 1) * SEC * SPC]
        img[lba(cl[k]) * SEC: lba(cl[k]) * SEC + len(chunk)] = chunk
    ents.append(entry(nm, 0x20, cl[0], size))
    expect.append((nm, cl[0], size, chk(data)))
# root folder: clusters 2, 30, 240
root = b''.join(ents) + bytes(32)                             # 00 = end of folder
assert len(root) <= 3 * SEC * SPC
fat[2], fat[30], fat[240] = 30, 240, 0x0FFFFFFF
for k, c in enumerate([2, 30, 240]):
    part = root[k * SEC * SPC:(k + 1) * SEC * SPC]
    img[lba(c) * SEC: lba(c) * SEC + len(part)] = part
for f in range(NF):
    struct.pack_into('<%dI' % len(fat), img, (FAT_LBA + f * FSZ) * SEC, *fat)

open(os.environ.get('IMAGE_OUT', 'tb_fat_image.hex'), 'w').write(''.join('%02x\n' % b for b in img))
with open(os.environ.get('EXPECT_OUT', 'tb_fat_expect.vh'), 'w') as f:
    f.write('// generated by mk_fat_image.py\nlocalparam integer NEXP = %d;\n' % len(expect))
    f.write('reg [87:0] exp_name [0:NEXP-1]; reg [31:0] exp_clus [0:NEXP-1], exp_size [0:NEXP-1], exp_chk [0:NEXP-1];\n')
    f.write('initial begin\n')
    for i, (nm, c, s, k) in enumerate(expect):
        f.write('  exp_name[%d] = "%s"; exp_clus[%d] = %d; exp_size[%d] = %d; exp_chk[%d] = 32\'h%08x;\n' % (i, nm, i, c, i, s, i, k))
    f.write('end\n')
print(len(ents), 'folder entries;', ', '.join('%s@%d' % (n.strip(), c) for n, c, s, k in expect))
